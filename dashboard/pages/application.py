import streamlit as st

st.set_page_config(layout="wide")
st.set_page_config(
    page_title="О системе",
    page_icon="🏠",
    layout="wide",
    initial_sidebar_state="expanded"
)

st.title("Аналитика продаж интернет-магазина")

with st.container(border=True):
    st.markdown("""
    ### Добро пожаловать в систему аналитики!

    Этот дашборд предоставляет интерактивную визуализацию данных о продажах интернет-магазина.

    **Используйте боковое меню для навигации:**

    **Базовая аналитика (доступна всем авторизованным пользователям):**
    - **Выручка по периодам** — анализ динамики выручки по дням с фильтрами по датам
    - **Топ товаров** — рейтинг самых продаваемых товаров по выручке
    - **Клиенты по городам** — географическое распределение заказов по городам
    - **Воронка конверсии** — анализ переходов между статусами заказов

    **Расширенная аналитика (доступна менеджерам):**
    - **Финансы и Маржинальность** — анализ прибыльности (выручка vs себестоимость)
    - **ABC-анализ** — категоризация товаров по принципу Парето (A/B/C)
    - **Временная аналитика** — паттерны покупок по дням недели, часам, месяцам
    - **Топ клиентов** — рейтинг VIP-покупателей по сумме покупок
    ---

    **Технологии:**
    - Backend: Django + PostgreSQL
    - API: REST (JSON)
    - Frontend: Streamlit + Plotly
    """)

with st.sidebar:
    st.header("ℹО системе")
    st.markdown("""
    - **Источник данных:** PostgreSQL
    - **Количество заказов:** ~10 000
    - **Период:** последний год
    - **Обновление:** в реальном времени
    """)